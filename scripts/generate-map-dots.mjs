#!/usr/bin/env node
// Builds the dotted map used by the Contact section (src/data/mapDots.js).
//
//   node scripts/generate-map-dots.mjs
//
// It downloads Natural Earth land and lake polygons (public domain), samples
// them on a regular grid and writes the land dots as one compact SVG path
// ("Mx yh0" with round caps = one dot each), so the map costs a few KB and no
// runtime library. Edit the constants below to change the region, density or
// the pinned location, then re-run.
import { writeFileSync } from "node:fs";

const BASE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson";
const REGION = { lonMin: -100, lonMax: -54, latMin: 28, latMax: 55 };
const STEP = 0.7; // grid spacing, in degrees of latitude
const PIN = { name: "Toronto", lon: -79.38, lat: 43.65 };
const NEAR_RADIUS = 3.2; // dots within this distance (map units) of the pin glow brighter

const midLat = (REGION.latMin + REGION.latMax) / 2;
const kx = Math.cos((midLat * Math.PI) / 180); // equirectangular, corrected for latitude
const project = (lon, lat) => [(lon - REGION.lonMin) * kx, REGION.latMax - lat];
const width = (REGION.lonMax - REGION.lonMin) * kx;
const height = REGION.latMax - REGION.latMin;

const load = async (name) => (await fetch(`${BASE}/${name}`)).json();
const [land, lakes] = await Promise.all([load("ne_110m_land.geojson"), load("ne_110m_lakes.geojson")]);

const polygons = (collection) =>
  collection.features.flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates));

const inRing = (lon, lat, ring) => {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
};
const inPolygon = (lon, lat, poly) => inRing(lon, lat, poly[0]) && !poly.slice(1).some((hole) => inRing(lon, lat, hole));
const inAny = (lon, lat, polys) => polys.some((p) => inPolygon(lon, lat, p));

const landPolys = polygons(land);
const lakePolys = polygons(lakes);
const [pinX, pinY] = project(PIN.lon, PIN.lat);

const all = [];
const near = [];
for (let y = STEP / 2; y < height; y += STEP) {
  const lat = REGION.latMax - y;
  // Offset every other row so the dots form a calm hexagonal lattice.
  const rowOffset = Math.round(y / STEP) % 2 ? STEP / 2 : 0;
  for (let x = STEP / 2 + rowOffset; x < width; x += STEP) {
    const lon = REGION.lonMin + x / kx;
    if (!inAny(lon, lat, landPolys) || inAny(lon, lat, lakePolys)) continue;
    const point = `M${x.toFixed(2)} ${y.toFixed(2)}h0`;
    all.push(point);
    if (Math.hypot(x - pinX, y - pinY) < NEAR_RADIUS) near.push(point);
  }
}

const out = `// Generated by scripts/generate-map-dots.mjs from Natural Earth (public domain). Do not edit by hand.
// One SVG path per layer: every \`Mx yh0\` with round caps draws one dot.
export const MAP = {
  width: ${width.toFixed(2)},
  height: ${height.toFixed(2)},
  step: ${STEP},
  pin: { name: ${JSON.stringify(PIN.name)}, x: ${pinX.toFixed(2)}, y: ${pinY.toFixed(2)} },
  dots: ${JSON.stringify(all.join(""))},
  near: ${JSON.stringify(near.join(""))},
};
`;
writeFileSync(new URL("../src/data/mapDots.js", import.meta.url), out);
console.log(`dots: ${all.length} (near the pin: ${near.length}), map ${width.toFixed(1)} x ${height}, file ${(out.length / 1024).toFixed(1)} KB`);
